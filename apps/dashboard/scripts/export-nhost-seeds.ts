/** Must match the space ids in `functions/dev-seed-users.ts`. */
const SPACE_IDS: Record<string, string> = {
  "vins-motors": "5c746831-a2b2-5770-a977-be49339c73f7",
  "prestige-rentals": "8f0c2d6e-4b1a-5c3d-9e7f-1a2b3c4d5e6f",
}

const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i

/** Stable UUID for fixture ids such as `client-1`, so re-running gives the same rows. */
function toUuid(id: string): string {
  if (SPACE_IDS[id]) return SPACE_IDS[id]
  if (UUID.test(id)) return id.toLowerCase()
  const hex = createHash("sha1").update(`autocore:${id}`).digest("hex").slice(0, 32).split("")
  hex[12] = "5"
  hex[16] = ((parseInt(hex[16], 16) & 0x3) | 0x8).toString(16)
  const h = hex.join("")
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-${h.slice(12, 16)}-${h.slice(16, 20)}-${h.slice(20)}`
}

type Value = string | number | boolean | null | undefined | object

function literal(value: Value): string {
  if (value === null || value === undefined) return "NULL"
  if (typeof value === "number") return Number.isFinite(value) ? String(value) : "NULL"
  if (typeof value === "boolean") return value ? "true" : "false"
  if (typeof value === "object") return `${literal(JSON.stringify(value))}::jsonb`
  return `'${value.replace(/'/g, "''")}'`
}

function insert(table: string, rows: Record<string, Value>[]) {
  if (rows.length === 0) return ""
  const columns = Object.keys(rows[0])
  const values = rows
    .map((row) => `  (${columns.map((column) => literal(row[column])).join(", ")})`)
    .join(",\n")
  return `INSERT INTO public.${table} (${columns.join(", ")}) VALUES\n${values}\nON CONFLICT (id) DO NOTHING;\n`
}

interface NamedJson {
  id: string
  business_space_id?: string | null
  slug: string
  name: { en: string; "zh-Hant"?: string }
  sort_order: number
  is_active: boolean
  [extra: string]: unknown
}

interface RangeJson {
  id: string
  slug: string
  label: { en: string; "zh-Hant"?: string }
  sort_order: number
  [extra: string]: unknown
}

function named(rows: NamedJson[], extras: string[]) {
  return rows.map((row) => ({
    id: row.id,
    business_space_id: row.business_space_id ? toUuid(row.business_space_id) : null,
    slug: row.slug,
    name_en: row.name.en,
    name_zh: row.name["zh-Hant"] ?? null,
    sort_order: row.sort_order,
    is_active: row.is_active,
    ...Object.fromEntries(extras.map((key) => [key, (row[key] as Value) ?? null])),
  }))
}

function range(rows: RangeJson[], extras: string[]) {
  return rows.map((row) => ({
    id: row.id,
    business_space_id: null,
    slug: row.slug,
    label_en: row.label.en,
    label_zh: row.label["zh-Hant"] ?? null,
    sort_order: row.sort_order,
    ...Object.fromEntries(extras.map((key) => [key, (row[key] as Value) ?? null])),
  }))
}

